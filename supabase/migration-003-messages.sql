-- ACHIRA — migration 003 : messages de l'équipe (onglet Messages de la dashboard).
-- Types : recrutement (trouver un membre pour un side / métier), projet (nouveau projet déposé),
--         candidature (nouvelle candidature), question (message d'un visiteur), note (note interne).
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('recrutement', 'projet', 'candidature', 'question', 'note')),
  title text not null check (char_length(title) <= 200),
  body text check (char_length(body) <= 3000),
  payload jsonb not null default '{}',
  author text check (char_length(author) <= 200),
  status text not null default 'new' check (status in ('new', 'read', 'done')),
  created_at timestamptz not null default now()
);
alter table public.messages enable row level security;
create policy "messages: tout pour les admins" on public.messages for all using (public.is_admin()) with check (public.is_admin());
-- le public peut seulement prévenir l'équipe (recrutement) ou poser une question, jamais relire
create policy "messages: envoi public" on public.messages for insert to anon, authenticated
  with check (type in ('recrutement', 'question') and status = 'new');
grant insert on public.messages to anon, authenticated;
revoke select, update, delete on public.messages from anon;

-- Messages automatiques à chaque projet déposé et à chaque candidature
create or replace function public.notify_project() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.origin = 'depot' then
    insert into public.messages (type, title, body, payload, author)
    values ('projet', 'Nouveau projet déposé : ' || left(new.title, 150),
            nullif(left(coalesce(new.story, ''), 600), ''),
            jsonb_build_object('slug', new.slug, 'secteur', new.disc),
            left(coalesce(new.submitter->>'name', ''), 200));
  end if;
  return new;
end $$;
drop trigger if exists projects_notify on public.projects;
create trigger projects_notify after insert on public.projects for each row execute function public.notify_project();

create or replace function public.notify_submission() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.messages (type, title, body, payload, author)
  values ('candidature', 'Nouvelle candidature : ' || left(new.name, 80) || ' (' || left(new.metier, 80) || ')',
          nullif(left(coalesce(new.msg, ''), 600), ''),
          jsonb_build_object('submission', new.id, 'project', new.project, 'domain', new.domain, 'metier', new.metier),
          left(new.name, 200));
  return new;
end $$;
drop trigger if exists submissions_notify on public.submissions;
create trigger submissions_notify after insert on public.submissions for each row execute function public.notify_submission();
